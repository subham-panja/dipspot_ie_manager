def get_all_sources(lead_type: Optional[str] = None, country: Optional[str] = None) -> List[Dict]:
    """Returns verified trade sources filtered optionally by lead type and country."""
    sources: List[Dict] = []
    if lead_type in ("importer", "importers", "buyer", "buyers"):
        sources = list(IMPORTER_SOURCES)
    elif lead_type in ("supplier", "suppliers", "wb_mill", "wb_mills", "mill", "mills"):
        sources = list(SUPPLIER_SOURCES)
    else:
        sources = list(IMPORTER_SOURCES) + list(SUPPLIER_SOURCES)

    if country and country.lower() not in ("all", "all countries", "global", ""):
        c_low = country.lower().strip()
        filtered = [
            s for s in sources
            if c_low in s.get("country_coverage", "").lower() or s.get("country_coverage", "").lower() == "global"
        ]
        if filtered:
            return filtered

    return sources


def get_importer_sources(country: Optional[str] = None) -> List[Dict]:
    return get_all_sources(lead_type="importer", country=country)


def get_supplier_sources(country: Optional[str] = None) -> List[Dict]:
    return get_all_sources(lead_type="supplier", country=country)
